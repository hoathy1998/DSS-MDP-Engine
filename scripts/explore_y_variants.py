"""Phase 2: can a different placement of the cost terms in Y reproduce Table 5? (assumption A3)

Keeps the structural readings that Table 5 and Fig. 7 confirm (A1 binomial, A2 p_on_second, Fig. 8 tree)
and tries each cost term per repair, per year, per accepted quote, per bid, flat, or absent.
This is a search for evidence, not a fit: results/y_variant_search.csv only informs the choice of Y.
"""
from __future__ import annotations

import csv
import itertools
from copy import deepcopy
from math import prod
from pathlib import Path

from dipmdp.data import load_decision_tree, load_koffer, load_paper_results
from dipmdp.decision_tree import tree_statistics
from dipmdp.evaluate import policy_statistics
from dipmdp.model import DIPModel, without_free_tasks
from dipmdp.solver import solve_recursive

OUTPUT = Path(__file__).resolve().parents[1] / "results" / "y_variant_search.csv"

MODES = {
    "repair": "E*B*H*P*{c}",
    "year": "E*H*P*{c}",
    "accept": "E*P*{c}",
    "bid": "E*{c}",
    "flat": "{c}",
    "none": "0",
}
REPAIR_COST_MODES = ("repair", "year", "accept")
REPAIR_COST = "A*(1-0.2*G)"


def main() -> None:
    data = load_koffer()
    tree = load_decision_tree()
    rows = []
    for a_mode, f_mode, i_mode in itertools.product(REPAIR_COST_MODES, MODES, MODES):
        expression = (
            f"E*B*H*P*f - {MODES[a_mode].format(c=REPAIR_COST)}"
            f" - {MODES[f_mode].format(c='F')} - {MODES[i_mode].format(c='I')}"
        )
        config = deepcopy(data)
        config["information_structure"]["variants"] = {"search": expression}
        config["information_structure"]["default"] = "search"

        tree_stats = tree_statistics(tree, DIPModel(config, y_method="plugin"))
        reduced_data, free = without_free_tasks(config)
        reduced = DIPModel(reduced_data, y_method="plugin")
        mdp = policy_statistics(reduced, solve_recursive(reduced).policy)
        for task in free:
            mdp.add_task(task["id"], 1.0, task["cost"])
        rows.append(
            {
                "a_term": a_mode,
                "f_term": f_mode,
                "i_term": i_mode,
                "expression": expression,
                "mdp_profit": round(mdp.expected_profit, 2),
                "mdp_revenue": round(mdp.expected_revenue, 2),
                "mdp_cost": round(mdp.avg_retrieval_cost, 2),
                "mdp_final_states": len(mdp.final_states)
                * prod(len(task["values"]) for task in free if "values" in task),
                "mdp_no_bid": round(mdp.decision_probs["No bid"], 3),
                "tree_profit": round(tree_stats.expected_profit, 2),
                "tree_revenue": round(tree_stats.expected_revenue, 2),
            }
        )

    table5 = load_paper_results()["table5"]
    target = table5["mdp"]["expected_profit"]
    rows.sort(key=lambda row: abs(row["mdp_profit"] - target))
    with open(OUTPUT, "w", newline="", encoding="utf-8") as f:
        f.write("# Phase 2 search over Y variants. Generated by scripts/explore_y_variants.py; deterministic.\n")
        f.write("# Fixed: A1 binomial, A2 p_on_second, Fig. 8 tree. Sorted by distance to the MDP profit of Table 5.\n")
        f.write(f"# Table 5 target: {table5['mdp']} | {table5['decision_tree']}\n")
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    print(f"wrote {OUTPUT} ({len(rows)} rows)")
    for row in rows[:8]:
        print(row)


if __name__ == "__main__":
    main()
