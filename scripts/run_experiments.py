"""Phase 4: evaluate all policies; write results/table5_repro.csv, table6_repro.csv and the Fig. 7 style charts."""
from __future__ import annotations

import csv
from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

from dipmdp.data import load_decision_tree, load_koffer, load_paper_results
from dipmdp.evaluate import PolicyStatistics, evaluate, simulate_policy
from dipmdp.model import DIPModel
from dipmdp.paper_figures import FIG7_DECISIONS, FIG7_TASKS
from dipmdp.policies import CollectAllPolicy, DecisionTreePolicy, MDPPolicy, MyopicVoIPolicy, RequiredOnlyPolicy
from dipmdp.solver import solve_array

RESULTS = Path(__file__).resolve().parents[1] / "results"
Y_VARIANTS = ("margin_all", "margin_repair")  # the chosen variant first (assumption A3)
PAPER_KEYS = {"mdp": "mdp", "decision_tree": "decision_tree"}
HEADER = "# Generated by scripts/run_experiments.py; deterministic, no random seed used. A1 binomial, A2 p_on_second, Fig. 8 tree.\n"

SERIES = {"mdp": ("MDP", "#2a78d6"), "tree": ("Cây quyết định", "#eb6834")}
SURFACE, INK, INK_SECONDARY, GRID, AXIS = "#fcfcfb", "#0b0b0b", "#52514e", "#e1e0d9", "#c3c2b7"
DECISION_LABELS = {2200: "2200", 2000: "2000", 1800: "1800", "No bid": "No bid"}
TASK_LABELS = {
    "2": "2", "A": "5 (A)", "B": "6 (B)", "D": "8 (D)", "F": "10 (F)",
    "G": "11 (G)", "H": "12 (H)", "I": "13 (I)", "alpha": "α",
}


def write_csv(path: Path, rows: list[dict[str, Any]], y_note: str) -> None:
    with open(path, "w", newline="", encoding="utf-8") as f:
        f.write(HEADER)
        f.write(f"# {y_note}\n")
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def table5_row(y_variant: str, name: str, stats: PolicyStatistics, table5: dict[str, Any]) -> dict[str, Any]:
    paper = table5.get(PAPER_KEYS.get(name, ""), {})
    profit = stats.expected_profit
    return {
        "y_variant": y_variant,
        "policy": name,
        "expected_profit": round(profit, 2),
        "expected_revenue": round(stats.expected_revenue, 2),
        "avg_retrieval_cost": round(stats.avg_retrieval_cost, 2),
        "n_final_states": len(stats.final_states),
        "no_bid_share": round(stats.decision_probs.get("No bid", 0.0), 4),
        "paper_profit": paper.get("expected_profit", ""),
        "paper_revenue": paper.get("expected_revenue", ""),
        "paper_cost": paper.get("avg_retrieval_cost", ""),
        "paper_final_states": paper.get("final_states", ""),
        "profit_diff_pct": round(100 * (profit / paper["expected_profit"] - 1), 1) if paper else "",
    }


def grouped_bars(
    path: Path,
    title: str,
    keys: list[Any],
    labels: dict[Any, str],
    model_shares: dict[str, dict[Any, float]],
    paper_shares: dict[str, dict[Any, float]],
) -> None:
    plt.rcParams["font.family"] = ["Segoe UI", "DejaVu Sans"]
    fig, ax = plt.subplots(figsize=(8.5, 4.4), facecolor=SURFACE)
    ax.set_facecolor(SURFACE)
    width, gap = 0.34, 0.02
    positions = range(len(keys))
    for offset, who in ((-(width + gap) / 2, "mdp"), ((width + gap) / 2, "tree")):
        name, color = SERIES[who]
        xs = [p + offset for p in positions]
        ax.bar(xs, [model_shares[who].get(k, 0.0) for k in keys], width, color=color, label=name, zorder=2)
        ax.scatter(
            xs,
            [paper_shares[who].get(k, 0.0) for k in keys],
            s=42,
            color=INK,
            edgecolors=SURFACE,
            linewidths=1.5,
            zorder=3,
            label="Bài báo (đọc từ Fig. 7)" if who == "mdp" else None,
        )
    ax.set_xticks(list(positions), [labels[k] for k in keys])
    ax.set_ylim(0, 1)
    ax.set_ylabel("Tỷ lệ hồ sơ", color=INK_SECONDARY)
    ax.yaxis.grid(True, color=GRID, linewidth=0.8, zorder=0)
    ax.tick_params(colors=INK_SECONDARY, length=0)
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color(AXIS)
    ax.set_title(title, loc="left", color=INK, fontsize=12, pad=30)
    ax.legend(frameon=False, ncols=3, loc="lower left", bbox_to_anchor=(0, 1.0), labelcolor=INK_SECONDARY, borderaxespad=0.2)
    fig.tight_layout()
    fig.savefig(path, dpi=200, facecolor=SURFACE)
    plt.close(fig)


def main() -> None:
    paper = load_paper_results()
    tree = load_decision_tree()
    table5_rows: list[dict[str, Any]] = []
    table6_rows: list[dict[str, Any]] = []

    for y_variant in Y_VARIANTS:
        model = DIPModel(load_koffer(), y_variant=y_variant, y_method="plugin")
        solution = solve_array(model)
        tree_policy = DecisionTreePolicy(tree, model)
        policies = [
            MDPPolicy(solution),
            tree_policy,
            RequiredOnlyPolicy(model),
            CollectAllPolicy(model),
            MyopicVoIPolicy(model),
        ]
        stats = {policy.name: evaluate(model, policy.act) for policy in policies}
        table5_rows += [table5_row(y_variant, name, s, paper["table5"]) for name, s in stats.items()]

        for row in paper["table6"]:
            true_values = dict(zip("ABCDEFGHI", row["final_state"]))
            mdp_run = simulate_policy(model, policies[0].act, true_values)
            tree_run = simulate_policy(model, tree_policy.act, true_values)
            table6_rows.append(
                {
                    "y_variant": y_variant,
                    "instance": row["instance"],
                    "final_state_ABCDEFGHI": " ".join(map(str, row["final_state"])),
                    "mdp_decision": mdp_run.decision,
                    "mdp_cost": round(mdp_run.cost, 2),
                    "mdp_profit": round(mdp_run.profit, 1),
                    "paper_mdp_profit": row["profit_mdp"],
                    "tree_decision": tree_run.decision,
                    "tree_cost": round(tree_run.cost, 2),
                    "tree_profit": round(tree_run.profit, 1),
                    "paper_tree_profit": row["profit_tree"],
                }
            )

        suffix = "" if y_variant == Y_VARIANTS[0] else f"_{y_variant}"
        shares = {"mdp": stats["mdp"], "tree": stats["decision_tree"]}
        grouped_bars(
            RESULTS / f"fig_decisions{suffix}.png",
            f"Phân phối quyết định cuối (Y = {y_variant})",
            [2200, 2000, 1800, "No bid"],
            DECISION_LABELS,
            {who: s.decision_probs for who, s in shares.items()},
            FIG7_DECISIONS,
        )
        grouped_bars(
            RESULTS / f"fig_task_usage{suffix}.png",
            f"Tỷ lệ thực hiện các tác vụ không bắt buộc (Y = {y_variant})",
            list(TASK_LABELS),
            TASK_LABELS,
            {who: s.task_usage for who, s in shares.items()},
            FIG7_TASKS,
        )

        mdp, tree_stats = stats["mdp"], stats["decision_tree"]
        print(
            f"{y_variant}: S3 gap={abs(mdp.expected_profit - solution.root_value):.2e}; S5 trend: "
            f"profit {mdp.expected_profit > tree_stats.expected_profit}, "
            f"fewer final states {len(mdp.final_states) < len(tree_stats.final_states)}, "
            f"higher cost {mdp.avg_retrieval_cost > tree_stats.avg_retrieval_cost}"
        )

    write_csv(RESULTS / "table5_repro.csv", table5_rows, "Paper columns come from Table 5, which has no row for the extra policies.")
    write_csv(RESULTS / "table6_repro.csv", table6_rows, "final_state column order as printed in Table 6, read as A..I (A5).")
    for row in table5_rows:
        print(row)


if __name__ == "__main__":
    main()
