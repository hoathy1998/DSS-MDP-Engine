"""Measure the deployment phase over real HTTP and write results/system_latency.json.

Tasks finish instantly here, so the figures show the system's own delay, not the delay of the tasks:
- recommender: time for one look-up;
- choice_to_new_advice: from sending a choice to receiving the response with the next advice;
- choice_to_push: from sending a choice to the live event channel delivering the next advice.
Each worker runs its own cases at the same time as the others.
"""
from __future__ import annotations

import json
import os
import platform
import threading
import time
import urllib.request
from pathlib import Path

from dipmdp.system.design import load_package
from dipmdp.system.engine import CaseEngine, SimulatedExecutor
from dipmdp.system.recommender import MDPRecommender
from dipmdp.system.server import make_server

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "results" / "system_latency.json"
WORKERS = 8
CASES_PER_WORKER = 25


def post(url: str, body: dict) -> dict:
    request = urllib.request.Request(url, json.dumps(body).encode(), {"Content-Type": "application/json"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.loads(response.read())


def summary(samples: list[float]) -> dict[str, float | int]:
    ordered = sorted(samples)
    return {
        "count": len(ordered),
        "median_ms": round(1000 * ordered[len(ordered) // 2], 3),
        "p99_ms": round(1000 * ordered[int(0.99 * len(ordered))], 3),
        "max_ms": round(1000 * ordered[-1], 3),
    }


def main() -> None:
    model, solution, integrated, manifest = load_package(ROOT / "results" / "deploy" / "koffer")
    engine = CaseEngine(MDPRecommender(model, solution), integrated, SimulatedExecutor())
    server = make_server(engine, manifest, port=0)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    base = f"http://127.0.0.1:{server.server_address[1]}/api/cases"

    response_times: list[float] = []
    push_times: list[float] = []
    collect = threading.Lock()

    def worker(worker_id: int) -> None:
        for index in range(CASES_PER_WORKER):
            view = post(base, {"seed": worker_id * 1000 + index})
            case_id = view["case_id"]
            arrivals: dict[int, float] = {}

            def listen() -> None:
                with urllib.request.urlopen(f"{base}/{case_id}/events", timeout=30) as stream:
                    for raw in stream:
                        line = raw.decode("utf-8").strip()
                        if line.startswith("data: "):
                            event = json.loads(line[6:])
                            if event["type"] == "recommendation":
                                arrivals[event["seq"]] = time.perf_counter()
                            if event["type"] == "case_closed":
                                return

            listener = threading.Thread(target=listen, daemon=True)
            listener.start()
            local_response, local_push = [], []
            while view["phase"] != "closed":
                sent = time.perf_counter()
                seq_before = view["last_seq"]
                view = post(f"{base}/{case_id}/actions", view["recommendation"]["best"])
                local_response.append(time.perf_counter() - sent)
                if view["phase"] != "closed":
                    # The advice is the last event the response reports.
                    deadline = time.perf_counter() + 5
                    while view["last_seq"] not in arrivals and time.perf_counter() < deadline:
                        time.sleep(0.0002)
                    if view["last_seq"] in arrivals and view["last_seq"] > seq_before:
                        local_push.append(arrivals[view["last_seq"]] - sent)
            listener.join(timeout=10)
            with collect:
                response_times.extend(local_response)
                push_times.extend(local_push)

    started = time.perf_counter()
    threads = [threading.Thread(target=worker, args=(i,)) for i in range(WORKERS)]
    for thread in threads:
        thread.start()
    for thread in threads:
        thread.join()
    seconds = time.perf_counter() - started
    server.shutdown()
    server.server_close()

    result = {
        "note": "Generated by scripts/measure_system.py. Client and server on one machine; tasks finish instantly.",
        "package": {key: manifest[key] for key in ("case", "y_variant", "n_states", "n_reachable", "solve_seconds")},
        "workers": WORKERS,
        "cases": WORKERS * CASES_PER_WORKER,
        "wall_seconds": round(seconds, 2),
        "cases_closed": sum(case["phase"] == "closed" for case in engine.list_cases()),
        "recommender": engine.latency_stats(),
        "choice_to_new_advice": summary(response_times),
        "choice_to_push": summary(push_times),
        "machine": {"platform": platform.platform(), "cpu_count": os.cpu_count(), "python": platform.python_version()},
    }
    OUTPUT.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
